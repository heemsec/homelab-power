'use strict';
// Unit checks for Play Billing entitlement on the web side (no device, no Play Store needed).
const assert = require('node:assert/strict');
let checks = 0;
const eq = (a, b, m) => { assert.deepEqual(a, b, m); checks++; };
const ok = (v, m) => { assert.ok(v, m); checks++; };
const entitlementPath = require.resolve('../entitlement.js');
const fresh = native => {
  delete require.cache[entitlementPath];
  if (native) globalThis.NativeBilling = {};
  else delete globalThis.NativeBilling;
  const E = require('../entitlement.js');
  delete globalThis.NativeBilling;
  return E;
};
let E = fresh(false);
eq(E.usesStore(), false, 'web build has no store');
eq(E.hasPro(), false, 'web free by default');
E.setPreview(true);
eq(E.hasPro(), true, 'web preview still grants');
eq(E.isPreview(), true, 'web preview readable');
E.setPreview(false);
E.setProvider(() => true);
eq(E.hasPro(), true, 'provider seam kept');
eq(E.isSupporter(), false, 'no supporter on web');
E = fresh(true);
eq(E.usesStore(), true, 'native starts in store mode');
eq(E.hasPro(), false, 'native locked before Play answers');
E.setPreview(true);
eq(E.hasPro(), false, 'preview cannot unlock native');
eq(E.isPreview(), false, 'preview reads false in native');
E.setProvider(() => true);
eq(E.hasPro(), false, 'provider cannot unlock native');
E.setStore({pro: true, supporter: false});
eq(E.hasPro(), true, 'purchased grants');
eq(E.isSupporter(), false, 'pro is not supporter');
E.setStore({pro: false, supporter: true});
eq(E.hasPro(), false, 'tip does not grant pro');
eq(E.isSupporter(), true, 'tip flag does not unlock pro');
E.setStore({pro: false, supporter: false});
eq(E.hasPro(), false, 'refunded or absent revokes');
E.setStore({pro: 'true', supporter: 1});
eq(E.hasPro(), false, 'only strict true grants');
eq(E.isSupporter(), false, 'only strict true supporter');
E.setStore(null);
eq(E.usesStore(), false, 'store can be cleared');
const B = require('../billing-ui.js');
const prices = {pro_unlock: '$2.99', tip_small: '$0.99', tip_medium: '$2.99', tip_large: '$4.99'};
let v = B.view({status: 'ready', prices});
eq(v.proLabel, 'Get Pro ($2.99)', 'localized pro price');
eq(v.tips[0].label, 'Small tip ($0.99)', 'localized tip price');
eq(v.proDisabled, false, 'can buy');
eq(v.tips[0].disabled, false, 'can tip');
v = B.view({status: 'ready', prices: {pro_unlock: '2,99 €', supporter_badge: '0,99 €'}});
eq(v.proLabel, 'Get Pro (2,99 €)', 'EUR string passed through untouched');
v = B.view({status: 'ready', prices, pro: true});
eq(v.proLabel, 'Pro is yours', 'owned label');
eq(v.proDisabled, true, 'owned not buyable');
ok(/yours/.test(v.status), 'owned status');
v = B.view({status: 'ready', prices, proPending: true});
eq(v.proLabel, 'Payment pending', 'pending label');
eq(v.proDisabled, true, 'pending not buyable');
eq(v.pro, false, 'pending not pro');
ok(/going through/.test(v.status), 'pending status');
v = B.view({status: 'ready', prices, supporter: true});
eq(v.supporter, false, 'no badge entitlement');
eq(v.tips[0].disabled, false, 'repeatable tip');
eq(v.pro, false, 'badge not pro');
v = B.view({status: 'ready', prices, pendingTips: ['tip_small']});
eq(v.tips[0].label, 'Tip pending', 'tip pending');
eq(v.tips[0].disabled, true, 'pending tip disabled');
eq(v.tips[1].disabled, false, 'other tips stay available');
v = B.view({status: 'ready', prices: {}});
eq(v.proLabel, 'Get Pro', 'no price yet');
eq(v.proDisabled, true, 'no product, no buy');
ok(/isn’t on sale/.test(v.status), 'products not set up');
v = B.view({status: 'unavailable', message: 'Google Play billing isn’t available on this device or account.'});
eq(v.proDisabled, true, 'unavailable disables pro');
eq(v.tips[0].disabled, true, 'unavailable disables tip');
ok(/isn’t available/.test(v.status), 'unavailable message');
v = B.view({status: 'unavailable', pro: true, source: 'cache'});
ok(/last time/.test(v.status), 'cache explained');
eq(v.pro, true, 'cached pro shown');
v = B.view(undefined);
ok(/Checking/.test(v.status), 'connecting default');
eq(B.view({status: 'connecting'}).proDisabled, true, 'connecting disables');
eq(B.outcomeMessage({outcome: 'purchased'}, 'pro_unlock'), 'Pro is yours. Thanks for supporting the app!', 'purchase msg');
ok(/Thanks for the tip/.test(B.outcomeMessage({outcome: 'purchased'}, 'tip_small')), 'tip msg');
ok(/pending/i.test(B.outcomeMessage({outcome: 'pending'})), 'pending msg');
ok(/Nothing was charged/.test(B.outcomeMessage({outcome: 'cancelled'})), 'cancel msg');
ok(/already own/.test(B.outcomeMessage({outcome: 'owned'})), 'owned msg');
eq(B.outcomeMessage({outcome: 'error', reason: 'X'}), 'X', 'error reason');
ok(B.outcomeMessage(null).length > 5, 'null outcome');
ok(/Restored\. Pro/.test(B.restoreMessage({status: 'ready', pro: true})), 'restore pro');
ok(/pending/.test(B.restoreMessage({status: 'ready', pendingTips: ['tip_small']})), 'restore pending tip');
ok(/No purchases/.test(B.restoreMessage({status: 'ready'})), 'restore none');
ok(/pending/.test(B.restoreMessage({status: 'ready', proPending: true})), 'restore pending');
ok(/Couldn’t reach/.test(B.restoreMessage({status: 'unavailable'})), 'restore offline');
B.start(undefined);
B.start({});
ok(true, 'start is a no-op without a window or bridge');
console.log(`PASS ${checks} billing unit checks`);
